//
// Builds the site the Worker serves, in web/site/ (git-ignored), laid out at its base path (ZC_BASE, default
// /chess/vs/) so every file is a static asset served without running the Worker:
//   1. core/ (rules, engine host, levels, board themes) copied to public/core/, as it is.
//   2. The lit piece sets, from ios/art through web/scripts/pieces.py, to public/pieces/.
//   3. public/ copied to site/<base>, with only the Zeist piece set, and js/config.js (where packs are downloaded from).
//   4. One page per engine, site/<base><id>/index.html, from pages/vs.html, and site/<base>engines.json, the list
//      Zeist's Chess reads for its picker. Both from the published catalog at engines.zei.st (ZC_CATALOG names a file
//      instead).
//   5. site/_headers: the pages' content security policy and the cache lifetimes.
//   6. site/<base>shell.js: every file of the app shell and a version from their contents, read by sw.js, and the
//      engine pins: the manifest_sha256 of every pack version this app may run (web/engine-pins.json, which keeps every
//      version ever listed, so a pack installed before a catalog change still runs). sw.js serves a pack's files only
//      when its manifest is pinned.
//
//   ZC_BASE   the path the pages are served under, default /chess/vs/
//   ZC_HOME   where Back goes: Zeist's Chess, default /chess
//   ZC_ORIGIN the site, for canonical addresses and share cards, default https://zeist.gg
//   ZC_PACKS  where packs are downloaded from, such as https://engines.zei.st/ once it answers this site with CORS
//             headers (web/README.md); unset, they come through the Worker at <base>engines/.
//
// Run: node web/scripts/assets.mjs

import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const web = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repo = path.dirname(web);
const pub = path.join(web, 'public');

const norm = b => { const s = String(b || '').trim().replace(/^\/*|\/*$/g, ''); return s ? `/${s}/` : '/'; };
const BASE = norm(process.env.ZC_BASE || '/chess/vs/');
const HOME = process.env.ZC_HOME || '/chess';
// The site the pages belong to, for their canonical address and share cards; and Zeist's Chess share image, the one
// its /chess page uses.
const ORIGIN = String(process.env.ZC_ORIGIN || 'https://zeist.gg').replace(/\/*$/, '');
const OG_IMAGE = process.env.ZC_OG_IMAGE || `${ORIGIN}/g/chess-og.jpg?v=3f782037`;
const OG_ALT = 'Chess and its board. The king of classics. Find your next checkmate.';
const PACKS = process.env.ZC_PACKS ? String(process.env.ZC_PACKS).replace(/\/*$/, '/') : null;
if (PACKS && !/^https:\/\/[a-z0-9.-]+\/$/.test(PACKS) && !/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?\/$/.test(PACKS)) throw new Error('ZC_PACKS must be an origin, such as https://engines.zei.st/');
const REPOSITORY = 'https://github.com/zeistgames/chess';
// Engines played by a rating instead of levels (Amrith, 2026-11-21: "a rating for Maia").
const BY_RATING = new Set(['maia']);
// Names under the base that are the app's own folders and files, never an engine's page.
const RESERVED = new Set(['engines', 'js', 'core', 'fonts', 'pieces', 'z', 'index', 'api', 'welcome', 'zeist']);

// 1. core
const coreOut = path.join(pub, 'core');
fs.rmSync(coreOut, { recursive: true, force: true });
for (const name of ['rules.js', 'host.js', 'levels.js', 'board-themes.json', 'vendor']) {
  fs.cpSync(path.join(repo, 'core', name), path.join(coreOut, name), { recursive: true });
}

// 2. pieces
execFileSync('python3', [path.join(web, 'scripts', 'pieces.py')], { stdio: 'inherit' });

// 3. the site, laid out at the base path
const siteRoot = path.join(web, 'site');
fs.rmSync(siteRoot, { recursive: true, force: true });
const site = path.join(siteRoot, ...BASE.split('/').filter(Boolean));
fs.mkdirSync(site, { recursive: true });
for (const e of fs.readdirSync(pub, { withFileTypes: true })) {
  if (e.name.startsWith('.') || e.name === 'pieces') continue;
  fs.cpSync(path.join(pub, e.name), path.join(site, e.name), { recursive: true });
}
fs.cpSync(path.join(pub, 'pieces', 'zeist'), path.join(site, 'pieces', 'zeist'), { recursive: true });
fs.writeFileSync(path.join(site, 'js', 'config.js'),
  `// Generated by web/scripts/assets.mjs. Where engine packs are downloaded from: an origin that sends CORS headers,\n` +
  `// or null for this site's own <base>engines/ (the Worker, reading the bucket).\n` +
  `export const PACKS = ${JSON.stringify(PACKS)};\nexport const HOME = ${JSON.stringify(HOME)};\n`);

// 4. the engines
// The published catalog, which is what the packs' server holds: a pack built but not yet published (engines/dist)
// would be listed and fail to download. ZC_CATALOG names a file instead (engines/dist/catalog.json to try local packs).
async function readCatalog() {
  if (process.env.ZC_CATALOG) return JSON.parse(fs.readFileSync(process.env.ZC_CATALOG, 'utf8'));
  const r = await fetch('https://engines.zei.st/catalog.json');
  if (!r.ok) throw new Error('the published catalog could not be read: set ZC_CATALOG to a catalog file');
  return r.json();
}
const catalog = await readCatalog();
const listed = (Array.isArray(catalog) ? catalog : catalog.engines || catalog.packs || []).filter(e => e && typeof e.id === 'string');
const order = JSON.parse(fs.readFileSync(path.join(repo, 'engines', 'order.json'), 'utf8'));
const rank = id => { const i = order.indexOf(id); return i < 0 ? order.length : i; };
const engines = listed
  .filter(e => /^[a-z0-9][a-z0-9-]{0,39}$/.test(e.id) && !RESERVED.has(e.id) && e.name)
  .sort((a, b) => rank(a.id) - rank(b.id));
const bytesOf = m => m.total_bytes || (m.files || []).reduce((a, f) => a + f.bytes, 0);
const say = n => n < 1e6 ? `${Math.max(1, Math.round(n / 1e3))} KB` : n < 1e7 ? `${(n / 1e6).toFixed(1)} MB` : n < 1e9 ? `${Math.round(n / 1e6)} MB` : `${(n / 1e9).toFixed(1)} GB`;
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
function licensesOf(m) {
  if (!m.license) return '';
  const program = m.license.replace(/ AND /g, ', ');
  const n = m.net_license;
  return !n || n === 'none' || n === m.license ? program : `${program}. Network: ${n}`;
}
function ratingRange(m) {
  const s = m.strength;
  const o = s && (s.uci_elo || ((s.type || s.kind) === 'uci_elo' ? s : null));
  return o && +o.min < +o.max ? [+o.min, +o.max] : null;
}
function face(id) {
  const f = path.join(repo, 'core', 'faces', `${id}.svg`);
  const svg = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '<svg viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="1.6"><circle cx="12" cy="12" r="6"/></svg>';
  return svg.trim().replace(/ xmlns="[^"]*"/, '').replace(/ (width|height)="\d+"/g, '').replace(/stroke="#000"/g, 'stroke="currentColor"');
}
const template = fs.readFileSync(path.join(web, 'pages', 'vs.html'), 'utf8');
// Titles, descriptions and headings for search, from web/seo.json: the default for every engine, overridden by id.
const SEO = JSON.parse(fs.readFileSync(path.join(web, 'seo.json'), 'utf8'));
function seo(m) {
  const o = { ...SEO.default, ...((SEO.engines || {})[m.id] || {}) };
  const fill = t => String(t ?? '').replace(/\{name\}/g, o.name || m.name).replace(/\{line\}/g, m.line || '').trim();
  return { title: fill(o.title), description: fill(o.description), h1: fill(o.h1) || 'Chess' };
}
const json = v => JSON.stringify(v).replace(/</g, '\\u003c');
for (const m of engines) {
  const range = BY_RATING.has(m.id) ? ratingRange(m) : null;
  const bytes = bytesOf(m);
  const level = (n, on) => `<button type="button" role="radio" aria-checked="${on}" data-level="${n}" aria-label="Level ${n}">${n}</button>`;
  const strength = range
    ? `<div class="pick"><span>Rating</span><div class="rate"><div class="rate-top"><b id="rating-value">1500</b><small>${range[0]} to ${range[1]}</small></div><input type="range" id="rating" aria-label="Rating" min="${range[0]}" max="${range[1]}" step="50" value="1500"></div></div>`
    : `<div class="pick"><span>Level</span><div class="lvls" id="lvls" role="radiogroup" aria-label="Level">${Array.from({ length: 10 }, (_, i) => level(i + 1, i === 2)).join('')}</div></div>`;
  const note = range
    ? `Plays like people at this rating. Your first game downloads it (${say(bytes)}).`
    : `Your first game downloads it (${say(bytes)}). After that it plays offline.`;
  const version = m.version && String(m.version).length <= 9 ? ` ${m.version}` : '';
  const about = `${m.name}${version}${m.author ? `, by ${m.author}` : ''}.${m.license ? ` License: ${licensesOf(m)}.` : ''}`;
  const data = { id: m.id, name: m.name, line: m.line || '', bytes, range };
  const page = template.replace(/<!-- SPDX[^>]*-->\n/, '').replace(/\{\{(\w+)\}\}/g, (_, k) => ({
    TITLE: esc(seo(m).title), SOCIAL_TITLE: esc(seo(m).title.replace(/ \| Zeist$/, '')),
    // The screen has room for "Chess" only, as on Zeist's /chess; the rest of the heading is for screen readers.
    H1: /^Chess /.test(seo(m).h1) ? `Chess<span class="vh">${esc(seo(m).h1.slice(5))}</span>` : esc(seo(m).h1),
    DESCRIPTION: esc(seo(m).description),
    CANONICAL: esc(`${ORIGIN}${BASE}${m.id}/`), OG_IMAGE: esc(OG_IMAGE), OG_ALT: esc(OG_ALT),
    DATA: json(data), NAME: esc(m.name), FACE: face(m.id), HOME: esc(HOME), STRENGTH: strength, NOTE: esc(note),
    ABOUT: esc(about), SOURCE: esc(`${REPOSITORY}/tree/main/engines/${m.id}`), REPOSITORY: esc(REPOSITORY),
  })[k] ?? '');
  fs.mkdirSync(path.join(site, m.id), { recursive: true });
  fs.writeFileSync(path.join(site, m.id, 'index.html'), page);
}
// Within what Zeist's picker reads (public/s/chess/engines.js there): at most 40 engines, names of 40 characters and
// lines of 90. Anything longer is cut here, and said, rather than cut there.
const LIMITS = { engines: 40, name: 40, line: 90 };
const cut = (t, n, what) => { if (t.length > n) console.warn(`engines.json: ${what} cut to ${n} characters`); return t.slice(0, n); };
if (engines.length > LIMITS.engines) console.warn(`engines.json: only the first ${LIMITS.engines} of ${engines.length} engines`);
fs.writeFileSync(path.join(site, 'engines.json'), JSON.stringify({
  format: 1,
  engines: engines.slice(0, LIMITS.engines).map(m => ({
    id: m.id, name: cut(String(m.name).trim(), LIMITS.name, `${m.id}'s name`), line: cut(String(m.line || '').trim(), LIMITS.line, `${m.id}'s line`), bytes: bytesOf(m),
  })),
}) + '\n');

// 5. headers: Cloudflare's static assets read site/_headers. Pages carry their own policy: engines run in workers from
// this origin and WebAssembly needs wasm-unsafe-eval; packs may be downloaded from PACKS; /api/me is read on this origin.
const CSP = [
  "default-src 'self'", "script-src 'self' 'wasm-unsafe-eval'", "worker-src 'self'",
  `connect-src 'self'${PACKS ? ' ' + new URL(PACKS).origin : ''}`,
  "img-src 'self' data: blob:", "style-src 'self' 'unsafe-inline'", "font-src 'self'", "base-uri 'none'",
  "object-src 'none'", "frame-ancestors 'none'", "form-action 'self'",
].join('; ');
fs.writeFileSync(path.join(siteRoot, '_headers'), `# Generated by web/scripts/assets.mjs
${BASE}*
  X-Content-Type-Options: nosniff
  Referrer-Policy: same-origin
${BASE}:id/
  Content-Security-Policy: ${CSP}
  Cache-Control: no-cache
${BASE}:id/index.html
  Content-Security-Policy: ${CSP}
  Cache-Control: no-cache
${BASE}engines.json
  Cache-Control: public, max-age=300
${BASE}sw.js
  Cache-Control: no-cache
${BASE}shell.js
  Cache-Control: no-cache
${BASE}fonts/*
  Cache-Control: public, max-age=2592000
${BASE}pieces/*
  Cache-Control: public, max-age=2592000
`);

// 6. the shell and the pins
const SKIP = new Set(['sw.js', 'shell.js', 'engines.json']);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, e.name);
    const rel = path.relative(site, p).split(path.sep).join('/');
    if (e.name.startsWith('.')) continue;
    if (e.isDirectory()) { walk(p); continue; }
    if (SKIP.has(rel) || /\.(txt|md|d\.ts|map)$/.test(e.name) && !rel.startsWith('fonts/')) continue;
    if (rel.startsWith('core/vendor/') && !rel.endsWith('.js')) continue;
    files.push(rel);
  }
})(site);
const pinsFile = path.join(web, 'engine-pins.json');
const pins = fs.existsSync(pinsFile) ? JSON.parse(fs.readFileSync(pinsFile, 'utf8')) : {};
for (const e of listed) {
  if (!/^[0-9a-f]{64}$/i.test(e.manifest_sha256 || '')) continue;
  (pins[e.id] ??= {})[e.manifest_sha256.toLowerCase()] = String(e.version);
}
const sorted = Object.fromEntries(Object.keys(pins).sort().map(id => [id, Object.fromEntries(Object.entries(pins[id]).sort())]));
fs.writeFileSync(pinsFile, JSON.stringify(sorted, null, 1) + '\n');
const pinCount = Object.values(sorted).reduce((a, v) => a + Object.keys(v).length, 0);
const h = createHash('sha256');
h.update(JSON.stringify(sorted));
for (const f of files) h.update(f).update(fs.readFileSync(path.join(site, f)));
const version = h.digest('hex').slice(0, 12);
// An engine's page is fetched as "<id>/", not "<id>/index.html".
const list = files.map(f => f.replace(/(^|\/)index\.html$/, '$1'));
fs.writeFileSync(path.join(site, 'shell.js'),
  `// Generated by web/scripts/assets.mjs. The app shell the service worker keeps for offline use.\n` +
  `self.SHELL = ${JSON.stringify({ version, files: list }, null, 1)};\n` +
  `// The engine pack manifests this app may run, by id: manifest_sha256 -> version (web/engine-pins.json).\n` +
  `self.PINS = ${JSON.stringify(sorted)};\n`);
console.log(`site ok at ${BASE}: ${engines.length} engines, ${files.length} shell files, ${pinCount} engine pins, version ${version}${PACKS ? `, packs from ${PACKS}` : ', packs through the Worker'}`);
