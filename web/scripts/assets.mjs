// Prepares web/public for serving. The app code itself has no build step; this only brings in what lives elsewhere
// in the repo and lists the app shell for the service worker:
//   1. core/ (rules, engine host, levels, board themes, piece sets) copied to public/core/, as it is.
//   2. The lit piece sets, from ios/art through web/scripts/pieces.py, to public/pieces/.
//   3. public/shell.js: every file of the app shell and a version from their contents, read by sw.js, and the engine
//      pins: the manifest_sha256 of every engine pack version this app may run (web/engine-pins.json, which keeps
//      every version ever listed, so a pack installed before a catalog change still runs; new entries come from
//      engines/dist/catalog.json when it is there). sw.js serves a pack's files only when its manifest is pinned.
// Generated folders are git-ignored. Run: node web/scripts/assets.mjs

import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const web = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repo = path.dirname(web);
const pub = path.join(web, 'public');

// 1. core
const coreOut = path.join(pub, 'core');
fs.rmSync(coreOut, { recursive: true, force: true });
const CORE = ['rules.js', 'host.js', 'levels.js', 'board-themes.json', 'piece-sets.json', 'vendor'];
for (const name of CORE) {
  fs.cpSync(path.join(repo, 'core', name), path.join(coreOut, name), { recursive: true });
}

// 2. pieces
execFileSync('python3', [path.join(web, 'scripts', 'pieces.py')], { stdio: 'inherit' });

// 3. the shell
const SKIP = new Set(['sw.js', 'shell.js']);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, e.name);
    const rel = path.relative(pub, p).split(path.sep).join('/');
    if (e.name.startsWith('.')) continue;
    if (e.isDirectory()) { walk(p); continue; }
    if (SKIP.has(rel) || /\.(txt|md|d\.ts|map)$/.test(e.name) && !rel.startsWith('fonts/')) continue;
    if (rel.startsWith('core/vendor/') && !rel.endsWith('.js')) continue;
    files.push(rel);
  }
})(pub);
// The pins: id -> { manifest_sha256: version }. Only ever added to.
const pinsFile = path.join(web, 'engine-pins.json');
const pins = fs.existsSync(pinsFile) ? JSON.parse(fs.readFileSync(pinsFile, 'utf8')) : {};
const catalogFile = path.join(repo, 'engines', 'dist', 'catalog.json');
if (fs.existsSync(catalogFile)) {
  const c = JSON.parse(fs.readFileSync(catalogFile, 'utf8'));
  for (const e of Array.isArray(c) ? c : c.engines || c.packs || []) {
    if (!e.id || !/^[0-9a-f]{64}$/i.test(e.manifest_sha256 || '')) continue;
    (pins[e.id] ??= {})[e.manifest_sha256.toLowerCase()] = String(e.version);
  }
}
const sorted = Object.fromEntries(Object.keys(pins).sort().map(id => [id, Object.fromEntries(Object.entries(pins[id]).sort())]));
fs.writeFileSync(pinsFile, JSON.stringify(sorted, null, 1) + '\n');
const pinCount = Object.values(sorted).reduce((a, v) => a + Object.keys(v).length, 0);

const h = createHash('sha256');
h.update(JSON.stringify(sorted));
for (const f of files) h.update(f).update(fs.readFileSync(path.join(pub, f)));
const version = h.digest('hex').slice(0, 12);
// The page itself is fetched as "./", not "index.html".
const list = files.map(f => (f === 'index.html' ? './' : f));
fs.writeFileSync(path.join(pub, 'shell.js'),
  `// Generated by web/scripts/assets.mjs. The app shell the service worker keeps for offline use.\n` +
  `self.SHELL = ${JSON.stringify({ version, files: list }, null, 1)};\n` +
  `// The engine pack manifests this app may run, by id: manifest_sha256 -> version (web/engine-pins.json).\n` +
  `self.PINS = ${JSON.stringify(sorted)};\n`);
console.log(`shell ok: ${files.length} files, ${pinCount} engine pins, version ${version}`);
